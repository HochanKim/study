# 준비: pandas 필요 없음. math 모듈만 씁니다.
# 각 문제의 기대 출력과 내 출력이 같으면 통과입니다.

import math

# 미지의 여행 데이터 (CH2)
x = [3, 6, 9, 8]  # 동행 수
y = [39, 70, 111, 93]  # 실제 만족도

# ----------------------------------------
# 문제 1. 오차 계산
# ----------------------------------------
# 모델 ŷ = w₁x₁ 에서 w₁ = 12 로 두고
# ① 네 여행지의 예측값 리스트, ② 오차(실제 − 예측) 리스트, ③ 오차의 합을 출력하세요.
# 힌트: 두 리스트를 같은 자리끼리 짝지어 도는 내장 함수가 있습니다.
# 기대 출력:
# [36, 72, 108, 96]
# [3, -2, 3, -3]
# 1
w1 = 12
ls01 = []

for x_num in x:
    ls01.append(x_num * w1)

print("① 네 여행지의 예측값 리스트:", ls01)

ls02 = []
for i in range(len(y)):
    ls02.append(y[i] - ls01[i])
print("② 오차(실제 − 예측) 리스트:", ls02)
print("③ 오차의 합:", int(math.fsum(ls02)))
print()

# ----------------------------------------
# 문제 2. SSE 함수 만들기
# ----------------------------------------
# w₁을 받아 오차 제곱합(SSE)을 돌려주는 함수 sse(w1)을 만들고
# w₁ = 9, 10, 12 일 때 값을 한 줄에 하나씩 출력하세요.
# 힌트: 리스트의 합을 구하는 내장 함수에 제곱한 값들을 바로 넣을 수 있습니다.
# 기대 출력:
# 1741
# 791
# 31


def sse(weight):
    # 예상치 계산
    yesang = []
    for i in x:
        yesang.append(i * weight)

    # 오차 계산
    diff_ls = []
    for j in range(len(y)):
        diff_val = y[j] - yesang[j]
        diff_ls.append(diff_val)

    # SSE
    sse_sum = 0
    for ss in diff_ls:
        # math 모듈의 제곱근 (숫자, 제곱할 값)
        sse_sum += int(math.pow(ss, 2))

    return sse_sum


print(sse(9))
print(sse(10))
print(sse(12))
print()

# ----------------------------------------
# 문제 3. SSE가 가장 작은 w₁ 찾기
# ----------------------------------------
# w₁을 0부터 24까지 정수로 바꿔 가며 sse(w1)을 계산해
# ① SSE가 가장 작은 w₁, ② 그때의 SSE, ③ 그때의 MSE(SSE ÷ 데이터 개수)를 출력하세요.
# 힌트: 반복문으로 돌려도 되고, "어떤 기준으로 가장 작은 것"을 골라 주는
#       내장 함수에 기준 함수를 넘겨도 됩니다.
# 기대 출력:
# 12
# 31
# 7.75

min_sse = sse(0)
small_w1 = 0
for w in range(25):
    if min_sse > sse(w):
        min_sse = sse(w)
        small_w1 = w
print(small_w1)
print(min_sse)
print(min_sse / len(y))
print()

