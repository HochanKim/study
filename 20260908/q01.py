# 문제 4. 시그모이드 함수
# ----------------------------------------
# σ(z) = 1 / (1 + e^(−z)) 를 함수 sigmoid(z)로 만들고
# z = −5, −1, 0, 1, 5 에 대해 "z 값" 형식으로 출력하세요. (소수 셋째 자리 반올림)
# 힌트: e의 거듭제곱을 계산해 주는 함수가 math 모듈에 있습니다.
# 기대 출력:
# -5 0.007
# -1 0.269
# 0 0.5
# 1 0.731
# 5 0.993


# 시그모이드 함수
def sigmoid(input):
    z = 1 / (1 + (2.718 ** (-input)))
    return z


z = [-5, -1, 0, 1, 5]

for i in z:
    print(i, round(sigmoid(i), 3))
print()

