# 문제 5. 시그모이드 모델로 만족 확률 예측하기
# ----------------------------------------
# 친구들의 여행 데이터 (CH3)
x1 = [1, 3, 5, 7, 10, 13, 15, 17, 20]  # 여행 횟수

p = [0.02, 0.05, 0.12, 0.23, 0.50, 0.77, 0.88, 0.95, 0.98]  # 실제 만족 확률
#
# ① 모델 ŷ = σ(0.4x₁ − 4) 의 예측값 리스트를 출력하세요. (소수 둘째 자리 반올림)
# ② 잘못 결합한 모델 σ(0.4x₁ − 10) 과 올바른 모델 σ(0.4x₁ − 4) 의
#    MSE를 각각 출력하세요. (소수 넷째 자리 반올림)
# 힌트: 문제 4의 sigmoid 함수를 그대로 쓰면 됩니다.
# 기대 출력:
# [0.03, 0.06, 0.12, 0.23, 0.5, 0.77, 0.88, 0.94, 0.98]
# 0.3568
# 0.0

# 올바른 모델
sigmoid_ls = []
for n in x1:
    sigmoid_ls.append(round(sigmoid(0.4 * n - 4), 2))
print(sigmoid_ls)

# 잘못 결합한 모델
wrong_ls = []
for n in x1:
    wrong_ls.append(round(sigmoid(0.4 * n - 10), 2))
# print(wrong_ls)


# mse 계산 함수
def mse(ls1, ls2):
    sse_ls = []
    for n in range(len(ls2)):
        # 실제 만족 확률과 오차 계산
        sse_ls.append(ls1[n] - ls2[n])

    sse_sum = 0
    # sse
    for i in sse_ls:
        # 오차 제곱합
        jegob = i**2
        sse_sum += jegob

    # mse
    mse = round(sse_sum / len(sse_ls), 4)

    return mse


print(mse(wrong_ls, p))  # 잘못 결합한 모델
print(mse(sigmoid_ls, p))  # 올바른 모델
