# 1. 이름과 겹칠때 우선 변수는?
# ============================================

name = "전역"


def show():
    name = "지역"  # 함수 안에 같은 이름의 변수가 있으면
    print(name)  # 지역 변수가 우선


show()
print(name)  # 전역

# 찾는 순서: 함수 안(지역) -> 함수 밖(전역) -> 파이썬 기본 기능
# 함수 안에 있으면 그걸 쓰고, 없으면 밖에서 찾습니다
# 절대 하지 말아야 할 것
# list = [1, 2, 3]  # list() 함수를 덮어 씀
# sum = 100 # sum() 함수를 덮어 씀
# max = 50  # max() 함수를 덮어 씀
# 에러 메시지도 이해하기 어려워서 원인을 찾기가 매우 힘듦


