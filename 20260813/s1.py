# ============================================
# 파일 다루기 - 경로부터 CSV까지
# ============================================

# 필요한 도구 가져오기
# pathlib: 경로를 다루는 도구 (파이썬에 기본 내장)
# csv: CSV 파일을 다루는 도구 (파이썬에 기본 내장)
# os: 운영체제 관련 도구
# 이 셋은 설치가 필요 없다. -> import만 하면 바로 사용 가능
from pathlib import Path
import csv
import os

# ============================================
# 경로란 무엇인가
# ============================================

# 경로(path)는 '파일이 어디 있는지 알려주는 주소'
# ex) C:\Users\ghcks\Documents\GitHub\study\20260813\s1.py
#     저장 드라이브 \ ... 폴더들 ... \ 파일이름

# 두 가지 종류
# 1. 절대경로 - 처음부터 끝까지 다 적은 것
# => C:\Users\ghcks\Documents\GitHub\study\20260813\s1.py
# 장점: 어디서 실행하든 항상 같은 파일을 가리킵니다
# 단점: 다른 컴퓨터에서는 안 됨 (사용자가 다르기 때문에)

# 상대경로 - 지금 있는 위치를 기준으로 적은 것
# ex) 20260813\s1.py
# 장점: 짧고 편함, 다른 컴퓨터에서도 작동
# 단점: '지금 있는 위치'가 어디냐에 따라 달라짐 <= 여기서 문제 발생

# 대부분은 '상대경로'를 사용, 그런데 "지금 있는 위치"가 뭘까?
# "현재 위치"는 내 파일 위치가 아닐 수 있다
# => 파이썬이 "data.txt 열어줘"라는 말을 들으면
# '어느 폴더'에서 찾아야 할지 정해야 한다
#
# 그 기준이 되는 곳을 '현재 작업 폴더'라고 한다
# current working directory => 줄여서 CWD
#
# ! 함정 !
# 현재 작업 폴더는 '내 .py 파일이 있는 폴더'가 아닐 수 있다
# VS Code에서 어떤 폴더를 열었는지, 터미널에서 어느 위치에서 실행했는지에 따라 달라진다
# => 내 파일 위치: C:\work\project\main.py
# => VS Code로 연 폴더 : C:\work <= work 폴더만 오픈한 상황 발생

# 현재 작업 폴더는 'C:\work'가 된다
# main.py에서 open("data.txt")을 하면
# C:\work\data.txt를 찾는다 (찾아야 할 project 폴더가 아닌)
# 파일이 project 폴더에 있으면 못 찾는다

print("현재 작업 폴더: ", os.getcwd())
print("이 파일의 위치: ", Path(__file__).parent)

# 용어 설명
#
# os.getcwd() : 현재 작업 폴더를 알려줌
#
# __file__ : 지금 실행중인 .py 파일의 경로, 파이썬이 자동으로 만들어 주는 변수, 앞뒤에 밑줄 두 개가 붙은건 '특별한 변수'라는 표시
#
# Path(__file__) : 경로를 Path 객체로 만든것으로 문자열보다 다루기 편해진다
#
# .parent: 그 파일이 들어있는 '폴더', 부모(parent) 폴더라는 뜻


# 해결책: 항상 '이 파일 기준'으로 경로를 잡는다
#
# BASE = Path(__file__).parent => 이 .py 파일이 있는 폴더
# DATA = BASE / "data"  => 그 안의 data 폴더
# DATA.mkdir(exist_ok=True) => 없으면 만들기

# 이렇게 하면 어디서 실행하던지 항상 같은 곳을 가리킨다
# 앞으로 파일을 다루는 모든 코드는 이렇게 시작
# 나중에 pandas로 CSV를 읽을 때도 똑같이 쓴다

BASE = Path(__file__).parent  # 이 파일이 있는 폴더
DATA = BASE / "data"  # 그 안에 data 폴더
DATA.mkdir(exist_ok=True)  # 폴더 만들기

print("기준 폴더:", BASE)
print("데이터 폴더:", DATA)
print("이제 어디서 실행하던 항상 같은 곳을 가리킨다")

# mkdir 옵션 설명
