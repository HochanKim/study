# 여기까지가 리스트를 닮은 배열

# -----------------------------
# 원소별 연산 - 반복 없이 한 번에
# -----------------------------
# 온도 전체에 2도씩 더해 보정하고 싶다고 합시다.
#
# 리스트라면 이렇게 했습니다.
# result = []
# for t in temps:
#   result.append(t+2) # 빈 그릇 + for + append 세박자
# 배열은 temps+2  한 줄이면 끝입니다.
# 배열 전체에 한 번 적은 연산이 '모든 값에 동시에' 적용
# 이걸 '원소별 연산' 이라고 부릅니다.
#
# temps : [82.0 91.5 78.2 88.0 95.1 80.4]
#  + 2      +2   +2   +2   +2   +2   +2
#          ------------------------------
#          [84.0 93.5 80.2 90.0 97.1 82.4]
# 핵심 : 반복을 우리가 적지 않습니다.
#       그 반복이 연산 기호(+) 안에 숨어서 자동으로 돕니다.
#       무엇을 계산할지만 적고 반복은 도구에 맡김
#
# (참고) 실무니 외부 자료에서는 원소별 연산을 흔히
# '백터 연산' '백터화 연산' 이라고도 부릅니다.
# 값 하나하나에 같은 계산을 한꺼번에 적용하는 '계산 방식'을
# 가르키는 말입니다. 이름만 다르고 같은 것

# 배열 전체에 한 번에
# temps + 2
# temps - 5
# temps * 2

# 더하기만이 아닙니다. 빼기 곱하기 나누기가 다 같은 방식으로
# 배열 전체에 한 줄로 적용됩니다.
# 우리가 보는 건 한 줄이지만, 그 안에서 반복이 대신 돌고 있음

# ------------------------------
# 배열과 스칼라 - 브로드캐스팅
# ------------------------------
#
# 방금 배열에 '숫자 하나'를 더했음
# 이때 그 숫자 하나를 '스칼라'라고 부릅니다.
# 여러 값이 묶인 배열과 구분해, 홀로 있는 값 하나를 가르키는 말입니다.
#
# 배열에 스칼라를 연산하면 그 스칼라가 배열의 모든 값으로 '퍼짐'
# 이렇게 한 값이 배열 전체로 퍼지는 걸 '브로드캐스팅'이라 함
# 방송(broadcast)이 한 곳에서 나가 모두에게 닿듯,
# 숫자 하나가 배열 전체에 뿌려지는 것입니다.
#
# temps * 1.8
#
#        1.8  ....    <- 1.8이 배열 길이 만큼 복제
# temps : 82.0 ....
# 스칼라는 홀로 있는 값이라 배열이 아무리 길어도
# 그 길이에 맞춰 퍼집니다. 길이를 따질 일이 없습니다.

# ---------------------------
# 배열과 배열 - 같은 자리끼리
# ---------------------------
# 원소별 연산은 '배열과 배열' 사이에서도 됩니다.
# 오전에 잰 온도 배열과 오후에 잰 온도 배열이 있으면,
# 두 배열을 그냥 빼거나 더하면 됩니다.
a = np.array([82.0, 91.5, 78.2])
b = np.array([80.0, 90.0, 79.0])

# a : 82.0 91.5 78.2
#      +    +    +
# b : 80.0 90.0 79.0
#     --------------
#     162.0 181.5 157.2

# 핵심 : '같은 자리끼리' 계산됩니다.
#     두 배열의 0번끼리, 1번끼리, 2번끼리 짝지어 연산 됨
print(a + b)
print(a - b)
# 여기엔 조건이 하나 있음 : 두 배열의 '길이가 같아야' 합니다.
# 자리끼리 짝을 지으려면 자리 수가 맞아야 함
# 세 개짜리와 네 개짜리는 짝지을 수 없음 (오류 남!)

# --------------------------
# 원소별 연산이 '빠른' 이유
# --------------------------
# 원소별 연산은 코드만 짧아지는 게 아니라 실제로 더 빠릅니다.
#
# Q. 왜 배열이 for보다 빠른가?
# A. temps + 2 라고 적으면, 그 반복 전체를 파이썬 밖의
#    '미리 최적화되어 컴파일된 내부 코드'에 통째로 넘겨 한꺼번에 처리
#
# Q. 리스트 for는 왜 느린가?
# A. for 반복은 값 하나를 꺼내고 더하고 담은 과장을
#    파이썬 언어 수준 에서 한 걸음씩 밟습니다.
#    값이 백만 개면 이 느린 과정을 백만 번 되풀이합니다.
#    게다가 리스트는 값마다 자료형이 다를 수 있어
#    하나씩 확인하며 도느라 더 느립니다.
#
# Q. 언제 차이가 커지는가?
# A. 값이 적을 땐 안 보이지만, 값이 많아질수록 크게 벌어집니다.
#    여섯 개면 눈 깜짝할 새 끝나 차이를 못 느끼지만,
#    수십만 수백만 개가 되면 원소별 연산의 힘이 진가를 발휘함
#
# 그래서 실제 설비에서 쏟아지는 대량의 측정값을 다루려면
# 짧고 빠른 방신이 반드시 필요합니다.
#
# 리스트 방식 = 빈 그릇을 옆에 두고, 값을 하나씩 꺼내 계산해 담기.
#            for로 반복을 손수 지휘 '여러 걸음'
# 배열 방식 = 묶음 전체 위에 연산을 통째로 얹기
#           모든 자리가 한꺼번에 바뀌는 '한 걸음'
#
# "각 값에 하는 계산이 서로 독립적인가?"
# 온도마다 2를 더하는 일은 첫 값과 둘째 값 계산이 서로 상관 X
# 이렇게 값마다 같은 계산을 독립적으로 하는 일이라면
# 배열의 '한 번에 얹는' 그림이 딱 맞습니다.

# 리스트 for vs 배열 한 줄 - 같은 결과
# 리스트 : 빈 그릇 + for + append 세 박자
result = []
for t in [82, 79, 85]:
    result.append(t + 5)

# 배열 : 산술 기호 한줄
print(np.array([82, 79, 85]) + 5)

# 배열은 새로운 계산을 하는 게 아니라
# 같은 계산을 훨씬 짧게 하는 것입니다.
# 값들에 같은 계산을 반복 적용하는 일을 만나면,
# for를 짜기 전에 "배열 연산 한 줄로 안 될까?"를 먼저 생각
# 반복이 보이면 배열로 묶으면 됨

# ----------------------------
# 비교 연산 - 배열이 기준을 넘는지
# ----------------------------
#
# 배열에 할 수 있는 연산은 산술만이 아닙니다. '비교'도 됨
# 온도 배열에서 어느 값이 경고 기준 85도를 넘는지 알고 싶다면?
#
# 배열에 codes > 85 라고 적으면,
# 각 값이 저마다 85를 넘는지 '판정' 한 결과가 나옵니다.
codes = np.array([82, 91, 78, 88, 95, 80])
print(codes > 85)

# codes : 82   91   78   88   95   80
#   > 85:넘나? 넘나? 넘나?  넘나? 넘나?  넘나?
#        False True False True True False
# 산술 연산이 배열 전체에 한 번에 적용됐듯,
# 비교도 배열 전체에 한꺼번에 적용됩니다.
# [False True False True True False]
#
# 중요: 결과가 '원래 값' 이 아니라 '판정' 입니다.
#     codes > 85는 넘는 값을 꺼내 주는 게 아니라,
#     각 자리가 넘는지 아닌지만 알려 줍니다.
#     값을 걸러 오는 건 다음 단계이고,
#     이 비교는 그 걸러 오기의 '재료'가 되는 판정을 만드는 일

# ---------------------------------
# 불리언 배열 - 참 거짓만 담긴 배열(마스크)
# ---------------------------------
#
# codes > 85 의 결과가 정확히 뭐 ?
# 각 자리에 참(True) 또는 거짓(False)이 담긴 '새 배열' 입니다.
# 원래 배열과 길이가 같은데, 값이 숫자가 아니라 참 거짓 으로 채워진 것
# 이걸 '불리언 배열' 이라고 부름
#
# 이 참 거짓 지도를 흔히 '마스크(mask)' 라고 부릅니다.
# 가릴 것과 통과시킬 것을 표시한 '덮개' 라는 뜻입니다.
# 참(True) = 조건을 만족하는 자리
# 거짓(False) = 만족하지 못하는 자리
# 이 마스크가 있으면 다음 단계에서
# 참인 자리의 값만 골라 뽑아낼 수 있습니다.

# -----------------------------------
# 불리언 인덱싱 - 조건으로 걸러내기
# -----------------------------------
#
# 참 거짓 지도(마스크)가 있으면 그 지도에서 '참인 자리의 값만'
# 뽑아 낼 수 있습니다.
# 불리언 배열을 그냥 대괄호 안에 넣습니다.

# 예전엔 조건에 맞는 것만 걸러 내려면 이렇게 했습니다.
# result = []
# for c in codes:
#     if c > 85:
#         result.append(c)
# 불리언 인덱싱은 이 전부를 '한 줄' 로 대체합니다.

# 참인 값만 뽑기
print("codes[codes > 85]= ", codes[codes > 85])
# [91 88 95]

print("codes[codes < 80]= ", codes[codes < 80])
# [78]

# 조건만 갈아 끼우면 어떤 필터든 됩니다.
# [절차]
# 1) 조건 정하기 : 걸러 낼 조건을 비교 연산으로 결정.
# 2) 마스크 만들기 : 비교가 참 거짓 배열을 만듦
# 3) 값 뽑기 : 마스크를 대괄호에 넣어 arr[마스크]. 참의 자리 값만

# 처음엔 두 줄로 나눠 마스크를 눈으로 확인하고, 익으면 한줄로 겹쳐 씀

mask = codes > 85  # 마스크를 따로 만들어 눈으로 확인
# codes[mask]

# -----------------------------
# 조건 만족 개수 - sum
# -----------------------------
#
# 값을 걸러 내는 것 말고, 조건을 만족하는 값이 몇개인지
# 세고 싶을 때도 많습니다.
# 경고 온도가 몇 번 나왔는지 같은 개수
#
# 마스크를 np.sum 으로 더하면 됩니다.
# 왜 참 거짓을 더했는데 개수 가 나올까?
# 파이썬에서 True은 1   False는 0 으로 셈함
# 참의 개수가 곧 그 합입니다.

# np.sum(codes > 85)  -> 3 (경고값)
# np.sum(codes <= 85) -> 3 (정상값)

# 예전 방식: 0으로 시작하는 세는 변수를 두고 for로 돌면서 if로 1씩 더하기
# 이제는 한 줄 같은 마스크를 대괄호에 넣으면 '값'이 뽑히고,
# sum에 넣으면 '개수'가 세어집니다.

# ---------------------------------
# 수학 함수 - np.sqrt 와 np.round
# ---------------------------------
#
# 산술 연산과 비교 말고도, 배열 전체를 한 번에 가공하는 방법이 하나 더 있음
# NumPy가 제공하는 '수학 함수' 입니다.
#
# 특별한 점: 값 하나가 아니라 '배열을 통째로' 받아 모든 값에 한번에 적용됩니다.
# for로 하나씩 꺼낼 필요 없이 배열을 통째로 넘기면 한꺼번에 처리
#
# np.sqrt = 제곱근 ("루트" - 제곱해서 그 값이 되는 수)
# np.round = 반올림 (둘째 인자 = 남길 소수점 자릿수)

np.sqrt(np.array([9.0, 16.0, 25.0]))
# [3. 4. 5.]

np.round(np.array([82.37, 91.55]), 1)
# [82.4 91.6]

# np.을 앞에 붙여 부르는 건 "NumPy가 제공하는 함수" 라는 뜻
# 배열을 넣으면 배열이 나오고, 그 안에서 모든 값이 한 번에 가공

# ------------------------------
# 단위 변환과 정규화
# ------------------------------
#
# 지금까지 배운 스칼라 연산이 실제로 어떻게 쓰이는지
#
# [사례 1] 단위 변환 - 섭씨를 화씨로
# 화씨 = 섭씨 * 1.8 + 32
# 배열이라면 c * 1.8 + 32를 그래도 적으면 됨
# 배열 전체에 곱하기와 더하기가 한 번에 적용되어
# 모든 온도가 한꺼번에 화씨로 바뀝니다.

c = np.array([20.0, 25.0, 30.0])
print(c * 1.8 + 32)  # -> [68. 77. 86.]

# [사례 2] 정규화
# 정규화 = "크기가 제각각인 값을 0~1 범위로 맞추기"
#         같은 잣대로 비교하려고 다듬는 일입니다.
# 각 값에서 최솟값을 빼고, (최댓값 - 최솟값) 으로 나눕니다.
# -> 가장 작은 값은 0, 가장 큰 값은 1, 나머지는 그 사이에 놓임

norm = np.array([82.0, 91.5, 78.2])
# (a - a.min()) / (a.max() - a.min())
print((norm - norm.min()) / (norm.max() - norm.min()))
# [0.28571429 1. 0.]

# 이 정규화 한 줄에 오늘 배운 게 다 녹아 있음
# - 배열에서 스칼라를 빼는 연산
# - 스칼라 나눗셈
# - min, max로 최솟값 최대값 꺼내기
# 예전이라면 여러 반복이 필요했을 일이 한 줄로 끝납니다.
# 단위 변환과 정규화는 데이터 분석에서 늘 나오는 '전처리' 인데,
# 원소별 연산이 이걸 몇 줄로 처리해 줍니다.

# 주의
# 배열 연산시 항상 길이가 같은지 확인!

# --------------------------
# 실습 - 배열 연산과 필터링
# --------------------------
# Step 1: 온도 여덟값
temp8 = np.array([80.0, 83.5, 79.0, 88.2, 91.0, 82.7, 86.4, 84.9])

# Step 2: 한 줄로 보정 (+1.5)
temp8 = temp8 + 1.5


sample = temp8 > 85.0
# Step 3: 기준 85 넘는 값만 걸러 내기
warm = temp8[sample]


# Step 4: 개수 세기
print(np.sum(sample))

# Step 5: 걸러낸 경고값들의 평균
avg = np.round(warm.mean(), 2)


# ----------------------------------------
# 여기까지 정리
# ----------------------------------------
#
#   [값 꺼내기 - 리스트와 같은 규칙]
#     arr[2]       번호로 값 하나 (0부터, 음수는 뒤에서)
#     arr[1:3]     슬라이싱 (시작 포함, 끝 제외)
#     arr[0] = 값  요소 변경 (배열은 가변)
#
