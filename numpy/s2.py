# """[배열에서 값을 어떻게 꺼내나?]
# 측정값을 배열 하나로 묶는 데까지 손에 익혔습니다.
# 이제 배열 안의 값을 하나씩 꺼내는 법부터 시작합니다.

# 값을 꺼내는 규칙이 리스트에서 쓰던 것과 똑같습니다.
# 새로 외울 게 없습니다. 리스트 대괄호 그대로
# """

import numpy as np

temps = np.array([82.0, 91.5, 78.2, 88.0, 95.1, 80.4])

# -----------------------
# 배열 인덱싱 - 번호로 값 하나 꺼내기
# -----------------------
# 값 하나를 지목해 꺼내는 것을 '인덱싱' 이라고 합니다.
# 리스트에서 하던 그 대괄호 그대로
# []
# 번호 : 0 1 2 3 4 5
# 뒤에서: -6 -5 -4 -3 -2 -1
# 리스트에서 익힌 한 칸 어긋남이 배열에서도 똑같습니다.

# 값을 꺼낼 때 쓰던 temps[0]을 등호 왼쪽에 두면
# 그 자리에 값을 넣어라
# 꺼내기와 넣기가 같은 대괄호로 갈립니다.

# temps[0] = 100  # 첫 번째 값을 82.0 -> 100.0으로 교체
# 이렇게 내용을 바꿀 수 있는 자료를 '가변' 이라고 부름
# 배열도 리스트처럼 가변입니다.
# 센서가 넘긴 값에 오류가 있어 다시 잰 값으로 교체할 때,
# 배열 전체를 새로 만들 필요 없이 그 한 자리만 고쳐 넣으면 됩니다.

# 주의: 배열은 '같은 자료형' 만 담습니다.
# 실수 배열에 문자열을 넣는 식으로 자료형이 어그나는 값은
