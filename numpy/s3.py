# 여러 설비의 시간대별 측정값을 2차원 배열로 만들고
# axis를 바꿔가며 열별, 행별 요약을 각각 뽑은 뒤
# 조건 통계로 기준을 넘는 값만의 요약까지 구한다

data2d = np.array([[82, 91, 75], [88, 79, 95]])
print("shape:", data2d.shape)  # => (2, 3)
print("시간대별 평균:", data2d.mean(axis=0))
print("설비별 평균:", data2d.mean(axis=1))
print("85 초과 개수:", (data2d > 85).sum())
print("85 초과 값 평균:", data2d[data2d > 85].mean())
# 조건 배열 (data2d > 85)로 걸러 낸 값은 2차원이든, 1차원이든
# 골라낸 값들이 한 줄로 이어져 나오므로 평균 개수를 그대로 구할 수 있음
