import numpy as np

# -----------------------------------
# 통계 함수 - 반복 없이 한 줄로
# -----------------------------------

# 온도 여섯 값이 담긴 배열
temps = np.array([82, 91, 75, 88, 79, 95])

# numpy 이전 평균 구하기
# total = 0 # 빈 그릇
# for t in temps: # 값을 하나씩 꺼내며
#   total += t  # 그릇에 더하고
# avg = total / len(temps)  # 개수로 나눔
print("합계:", temps.sum())
print("평균:", temps.mean())
print("최대값:", temps.max())
print("최소값:", temps.min())
# => max와 min은 데이터의 '양 끝'을 알려준다
# => 평균이 중심값이라면, 최대와 최소는 값들이 흩어진 '범위의 폭'이다

# -----------------------------------
# 표준편차와 분산 - std, var
# -----------------------------------
"""
[값들이 얼마나 흩어져 있는가?]
평균 온도가 똑같이 85인 두 설비가 있다고 가정
- 한쪽은 84, 85, 86처럼 촘촘히 모여 있고 // 다른 한쪽은 70, 85, 100처럼 넓게 흩어져 있다

평균만 보면 같지만 뒤쪽이 훨씬 불안정함
=> 이 '흩어진 정도'를 한 숫자로 재는 것이 표준편차(std)이다

분산(var)은 흩어짐을 '제곰으로 잰 것'이라 값이 더 크다
둘 다 흩어짐을 재는 같은 목적임

수학은 여기서 직관만 잡을 뿐, 공식 외우지 않음
- 표준편차 = 평균에서 데이터가 얼마나 퍼져 있나
- 분산 = 퍼짐을 제곱으로 잰 것
(편차제곱합 나누기 n 같은 밑바닥 공식은 나중에 직접 재구현 할 예정이니 여기선 도구로 사용만)

"""

print("표준편차:", temps.std())
print("분산:", temps.var())
# => 손으로 구하려면 각 값에서 평균을 빼고, 제곱하고, 더해 나누고, 제곱근까지 씌워야 한다.
#   배열은 그 모든 과정을 std/var 한 줄에서 담는다
#   복잡한 계산일수록 배열 한 줄의 편함이 더 크게 드러남

# -----------------------------------
# 표준편차가 말하는 것
# -----------------------------------
#
# 꼭 기억해야 할 것
# => 두 설비의 평균이 똑같이 85도여도, 한 쪽은 촘촘하고 다른 한 쪽은 들쭉날쭉하면 실제로는 '완전히 다른' 설비이다
# => 평균 하나만으로 이 차이가 보이지 않음
#
# ☆ std는 바로 이 차이를 잡아낸다
# - std가 작으면 -> 값들이 평균에 몰려 있음 -> 안정적
# - std가 크면 -> 값들이 넓게 퍼져 있음 -> 불안정

# 평균으로 '중심'을, 최대 최소를 '양 끝'을, std로 '흩어짐'을 재면
# 데이터의 성격이 상당히 또렷해진다.


# [여섯 통계 함수를 세 성격으로 묶어 기억하기]
#
# 양 | sum | 배열 안 모든 값을 더한 총량, 전체 규모
# 위치 | mean max min | 중심과 양 끝이 어디인지
# 흩어짐 | std var | 값들이 중심에서 퍼진 정도
#
# => 궁금한 게 '양 위치 흩어짐' 중 무엇인지만 정하면 부를 함수가 정해진다
#   그 한줄이면 수백 개의 값이 숫자 몇 개로 압축 될 수 있다


# -----------------------------------
# axis (축, 방향) - 두 방향, 방향을 정해 주는 손잡이
# -----------------------------------

# ☆ axis의 개념 - 두 방향
#   지금까지 한 줄짜리 배열에서는 sum에 고민이 없었음
#   -> 값이 한 줄로만 늘어서 있으니 더할 방향이 하나 뿐이었다
# [82 91 75] -> 더하면 248

# 그런데 실제 데이터는 대개 '표' 모양 -> 행과 열이 있는 격자
# 설비 두 대의 시간대별 온도를 표로 적으면?
#         9시       10시       11시
# 1호기 [ 82         91         75  ]   <= 열 = 시간대
# 2호기 [ 88         79         95  ]   <= 행 = 설비
#
# 이 표를 놓고 "합계"를 요청하면 되묻게 된다
# ???: 설비별로? -> 가로로 더하기 (1호기 248, 2호기 262)
# ???: 시간대별로? -> 세로로 더하기 (9시 170, 10시 170, 11시 170)
# 답이 둘로 갈린다 -> 방향이 둘이니 어느 쪽인지 정해 줘야 한다
# 방향을 정하는 손잡이가 바로 'axis(엑시스, 축)'이다
#
# ※ axis는 '무엇을 계산할지'를 바꾸는 것이 아니다 ※
# => sum은 그냥 덧셈식
# => axis는 '어느 쪽으로 훑을지'만 정한다

# 무엇을 계산할지 -> 함수 이름(sum, mean, max, min, std, var)
# 어느 방향으로 -> axis

# 이 둘은 서로 상관없이 따로 논다 -> 그래서 함수 여섯 개의 X 방향


# -----------------------------------
# axis 번호는 어디서 온 숫자? shape의 자리 번호
# -----------------------------------
#
# 여기서 한 번은 막히는 구간 -> shape으로 보면 한 번에 풀린다
# ex) grid.shape(2, 3)
# 0번 자리 = 행 개수 2 -> 이게 axis=0
# 1번 자리 = 열 개수 3 -> 이게 axis=1
#
# axis 번호는 새로 외울 개념이 아니라
# 그냥 'shape 튜플의 몇 번째 자리인가?'를 의미
# 이미 배운 shape를 그대로 가리키는 번호
#
# 규칙은 한 줄로 끝난다 => axis에 지정한 그 자리가 shape에서 사라진다
#
# axis=0 -> (2, 3)에서 2가 사라짐 -> (3,) 값 3개 (열 수만큼)
# axis=1 -> (2, 3)에서 3이 사라짐 -> (2,) 값 2개 (행 수만큼)
# axis 없음 -> 둘 다 사라짐 -> 값 1개 (표 전체를 하나로)
#
# 이 규칙이 좋은 이유
# : 실행하기 '전에' 결과가 몇 개 나올지 맞힐 수 있다
#   => 나온 값의 개수가 예상과 다르면 axis를 반대로 준 것이니 바로 알 수 있다


# -----------------------------------
# 2차원 배열 만들기 - 리스트 안에 리스트
# -----------------------------------

# axis를 다루려면 먼저 방향을 가진 배열 (즉 2차원 배열이 필요함)
# 1차원 리스트 하나를 np.array에 넣음
# 2차원은 여기서 한 단계 더 들어간다 - 리스트 안에 리스트를 넣는 것
#
# 바깥 리스트 [ '안쪽 리스트1' '안쪽 리스트 2' ]
# 안쪽 리스트 하나 = 표의 한 '행'
#
#         열0       열1       열2     <= 시간대 (3개)
# 행0 [ 82          91         75  ]   <= 첫 번째 설비
# 행1 [ 88          79         95  ]   <= 두 번째 설비
grid = np.array([[82, 91, 75], [88, 79, 95]])
# 2차원 배열
print(grid)

print("shape:", grid.shape)  # => shape: (2, 3)
# 앞의 2 = 행 수, 뒤의 3 = 열 수, 설비 2대, 시간대 3개
# shape가 '두 숫자'로 나오는 것 자체가 이 배열이 2차원이라는 표시
# => 주의: 안쪽 리스트들의 길이는 모두 같아야 한다, 표는 각 행의 칸 수가 같아야 반듯한 격자가 됨

# -----------------------------------
# 2차원 인덱싱 - 대괄호 안에 [행, 열]
# -----------------------------------

# 1차원은 인덱스 하나로 값을 꺼냈지만,
# 2차원은 위치를 정하는 데 숫자가 두 개 필요합니다 - 행 번호, 열 번호
# 번호는 언제나 0부터

print("grid[1, 2] =", grid[1, 2])  # 95
# 앞 숫자 1 = 1번 행(두 번째 줄 [88 79 95])
# 두 숫자 2 = 그 줄의 2번 열(세 번째 값 95)
# 순서: 세로로 몇 번째 줄인지 '먼저', 가로로 몇 번째 칸인지 '나중'

print("grid[0] =", grid[0])  # -> grid[0] = [82 91 75]
# 행 번호만 적으면 그 행 '전체'가 나온다
# 이렇게 뽑은 한 행은 그 자체로 1차원 배열이라
# grid[0].mean()처럼 다시 통계를 걸 수 있다
# 다만 한 행씩 뽑아 따로 요약하는건 번거로움
# 그 일을 한 번에 하는 방법이 바로 다음의 axis 지정


# -----------------------------------
# axis 방향 모델 - '누르는 방향'
# -----------------------------------

# axis는 노베이스가가장 자주 막히는 지점 => 그래서 '누른다'는 하나의 그림으로 완전히 고정
#
# [세로로 누르기] axis=0
#   => 표를 위에서 아래로 누르면 -> 행이 접혀 사라지고 열만 남음
#
# 82  91  75   ↓
# 88  79  95   ↓
# -------------
# 170 170 170 <- 열별 결과 (열 수만큼 3개)
#
#
# [가로로 누르기] axis=1
#   => 왼쪽에서 오른쪽 누르면 -> 열이 접혀 사라지고 행만 남음
# →  82  91  75   -> 248  (행별 결과)
# →  88  79  95   -> 262  (행별 결과)
#
# [axis 없음]
#   => 방향 구분 없이 표 전체 값 여섯 개를 몽땅 요약

print("axis=0 (세로를 눌러 열별):", grid.sum(axis=0))
print("axis=1 (가로를 눌러 행별):", grid.sum(axis=1))
print("axis 없음 (전체):", grid.sum())

# 앞의 shape 규칙과 이 그림은 같은 말
# 'axis'에 준 그 방향이 접혀 사라진다
# 세로로 누르면(axis=0) 세로가 접혀 없어지고 -> 열별 값만 남음

# 정말 그 자리가 사라져쓴지 shape로 확인
print("aixs=0 결과 모양:", grid.sum(axis=0).shape)
print("aixs=1 결과 모양:", grid.sum(axis=1).shape)

# 원래 (2, 3) 이었음, axis=0을 주니 2가 빠짐
# 원래 (2, 3) 이었음, axis=1을 주니 3이 빠짐

# [현장에서 쓰는 말을 옮기자면...]
# => 행이 '무엇을(설비)', 열이 '언제(시간대)'를 뜻할 때
# ==> "시간대별 평균은?"  -> 열별 결과가 필요 -> axis=0
# ==> "전체 평균은?"  -> 방향 구분 없음 -> axis 안줌
#
# 즉 axis는 어느 것을 뭉갤지를 고르는 손잡이와 같음
# 시간대별로 보고 싶으면 설비를 뭉개고 (axis=0),
# 설비별로 보고싶으면 시간대를 뭉갠다(axis=1)


# -----------------------------------
# axis는 모든 통계 함수에 똑같이 적용
# -----------------------------------

# '누르는 그림'이 강력한 이유
# sum 뿐 아니라 mean, max, min, std 모두에 똑같이 적용되기 때문
# axis를 주는 자리와 방향이 눌린다는 그림은 함수가 뭐든 그대로
print("열별 평균:", grid.mean(axis=0))  # 열별 평균
print("행별 평균:", grid.mean(axis=1))  # 행별 평균

# grid.mean(axis=0): 세로로 눌러 각 '열(시간대)'의 평균
# 세 값 모두 85 -> 시간대 마다 두 설비 평균이 85도였다는 의미

# grid.mean(axis=1): 가로로 눌러 각 '행(설비)'의 평균
# 첫 설비 약 82.7 / 둘째 설비 약 87.3
#
# axis 숫자 하나만 바꿨을 뿐인데 '시간대별 요약'과 '설비별 요약'이 갈린다
# 설비별 평균(각 행의 평균)을 구하려면 axis에 무엇을 주면 되나
# -> 가로로 눌러 행별 결과를얻는 axis=1을 주면 됨

# mean 만이 아니라 max, min, std도 자리와 의미가 똑같음
print("시간대별 최고 온도:", grid.max(axis=0))
print("설비별 최고 온도:", grid.max(axis=1))
print("설비별 흩어짐:", grid.std(axis=1))

# 두 설비의 std가 같음 -> 평균은 달라도 들쭉날쭉한 정도는 비슷하다는 뜻

# -----------------------------------
# axis에서 자주 하는 실수 두 가지
# -----------------------------------
# [실수 1] 1차원 배열에 axis=1을 준다
# => 1차원은 shape(2,) 처럼 자리가 하나뿐이라 axis는 0 밖에 없음
# ==> 그런데 표인 줄 알고 axis=1을 주면 오류가 난다

# [실수 2] axis=0을 '행별'로 착각한다
# => 0번이 첫 번째니까 행이겠거니 하고 넘겨 짚으면 안됨
# ==> axis=0은 0번 축(행 방향)을 "따라 훑는" 것이라 행이 뭉개지고 열이 남음
# 헷갈릴 때마다 shape 규칙을 참고
# (2, 3)에서 axis=0 => 행인 2가 사라짐 => 남는건 열 3, 즉 열별 예외를 적용

# -----------------------------------
# 센서 배열 통계 분석
# -----------------------------------

# 한 설비의 측정값 배열을 만들고, 여섯 통계 함수를 차례로 적용해
# 데이터 성격을 '숫자 몇 개'로 압축하는 흐름을 확인
# (케이스 A 온도 / 케이스 B 진동 - 하는 일은 같습니다. 여기선 온도)
print()
sensor = np.array([82, 91, 75, 88, 79, 95])  # 설비 M-101 온도 여섯 개의 값
print("[센서 요약]")
print("총합:", sensor.sum())
print("평균:", sensor.mean())
print("최대:", sensor.max())
print("최소:", sensor.min())
print("표준편차:", sensor.std())
print("분산:", sensor.var())
# => 이 여섯 숫자만으로 "평균 85도 근처, 75~95 사이에 값이 제법 흩어졌다"

# -----------------------------------
# 형태 바꾸기: reshape, concatenate
# -----------------------------------

# reshape - 값은 그대로, 행 열 배치만 바꾸기
# => 한 줄로 죽 늘어선 여섯 값을 '두 설비 세 시간대'의 표로 보고 싶을 때가 있다
# => 값은 그대로인데 배치만 바꾸는 것 - 이 함수가 바로 reshape

a = np.arange(6)  # [0 1 2 3 4 5]
b = a.reshape(2, 3)  # 2행 3열의 표로 접기
print(b)  # -> reshape을 하니까 2차원 배열로 생성 [[0 1 2] [3 4 5]]
# => reshape에 준 두 숫자(2, 3)가 세 모양의 행 수와 열 수이다
# 값 0~5는 그대로, 앞에서부터 세 개씩 끊어 두 줄로 놓임
print()

# 반드시 지킬 규칙: 바꾸기 전과 후의 '값 개수'가 딱 맞아야 한다
# 여섯 값은 2X3 or 3X2 로는 접히지만, 2X4(8칸)은 불가능
# => 두 숫자를 곱한 값이 원래 개수와 같은지 먼저 확인함

# 개수가 안맞으면 에러가 남
# => reshape는 값을 새로 만들거나 버리는 게 아니라, 있는 값을 '재배치'하는 것
# => 그래서 틀의 칸 수가 값의 개수와 정확히 맞아야 함


# concatenate - 배열 이어붙이기
# => 데이터가 여러 조각으로 나뉘어 들어오는 경우가 많음
# => 오전에 잰 값과 오후에 잰 값이 따로 있는 식

# 함께 분석하려면 하나의 배열로 이어 붙어야 한다
# => 그 함수가 바로 'concatenate'이다

# ※ 주의: 이어 붙일 배열들을 '리스트에 담아' 넘긴다 -> ex) [x, y]

x = np.array([82, 91])  # 오전 데이터
y = np.array([75, 88])  # 오후 데이터
z = np.concatenate([x, y])
# [82 91 75 88]

# 합친 배열에는 앞서 배운 통계 함수를 그대로 적용할 수 있다
# => 나눠 들어온 데이터를 하나로 모아 전체 평균이나 최댓값을 구함
# z.mean() => 합친 뒤 평균: 84.0

# [2차원을 이어 붙일 때는 axis로 방향]
# axis=0 -> 세로로 쌓기, 행을 아래에 붙여 표를 넓게 늘림
# axis=1 -> 가로로 붙이기, 열을 옆에 붙여 표를 넓게 늘림
# 크기 규칙: 붙이는 방향이 '아닌' 쪽의 크기가 맞아야 함
# => 세로로 쌓으려면 열 수가 같아야, 가로로 붙이려면 행 수가 같아야

# ※ 주의: 같은 axis인데 의미가 반대
# => 통계 함수 axis -> 그 방향이 눌려서 '사라진다'
# ====> concatenate의 axis -> 그 방향으로 붙여서 '늘어난다'
#
# grid.sum(axis=0) -> 행이 사라져 값 3개로 줄고
# concatenate(axis=0) -> 행이 늘어나 표가 길어진다. (정반대의 역할)
# => 한 문장으로 표현하자면, "통계의 axis는 줄이는 방향, concatenate의 axis는 늘리는 방향"
# => reshape가 한 배열의 틀을 바꾸는 것이라면, concatenate는 여러 배열을 합쳐 더 큰 틀로 키우는 것


# -----------------------------------
# 조건 통계 - 경고값만 골라 평균
# -----------------------------------
#
# 전체가 아니라 '조건에 맞는 값만' 요약하고 싶을 때 많음
# => 전체 평균이 아니라, 기준을 넘는 '경고값'들만의 평균과 같은 값
# => 조건부 요약은 '불리언 인덱싱 + 통계 함수'를 이어 붙여 만듦

# 'temps > 85'는 각 값이 85를 넘는지를 True/False로 담은 배열
print("조건 배열:", temps > 85)  # [False True False True False True]

# ※ where 메서드
over = temps > 85
print("where로 조건에 맞는 열의 자리(인덱스):", np.where(over)[0])

# temps[temps > 85] 는 조건이 True인 값만 골라 낸 새 배열
# -> 85를 넘는 91, 88, 95만 남는다. 여기에 .mean()을 이어 붙인다
print("경고값 평균:", temps[temps > 85].mean())
# => 전체 평균 85와는 다른, "경고 상황"만의 평균

# 개수 세기는 조금 특별하다
# => 불리언 배열에 바로 sum을 걸면 True=1, False=0으로 세어지므로
# => 'True의 합' = '조건을 만족한 값의 개수'가 됩니다
print("경고값 개수:", (temps > 85).sum())  # 경고값 개수 3
print()

# 조건으로 거른 뒤 요약하는 이 흐름은 실제 데이터 분석에서 가장 자주 쓰는 방법이다
# 이상값만의 평균, 정상갑의 개수처럼 특정 부분만 볼 수 있다


