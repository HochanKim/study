import numpy as np

# 설비 3대 x 시점 5개 온도표입니다. 이 파일 전체에서 씁니다.
#              t1    t2    t3    t4    t5  -> axis=0
# 1호기 ->   [71.2, 68.5, 75.9, 80.1, 66.3] --
# 2호기 ->   [69.8, 72.4, 78.2, 85.6, 70.0]  |  -> axis=1
# 3호기 ->   [74.1, 70.9, 69.5, 77.3, 81.8] --
temp = np.array(
    [
        [71.2, 68.5, 75.9, 80.1, 66.3],
        [69.8, 72.4, 78.2, 85.6, 70.0],
        [74.1, 70.9, 69.5, 77.3, 81.8],
    ]
)


# ----------------------------------------
# 문제 1. 2차원 슬라이싱 두 방향 동시에
# ----------------------------------------
# temp에서 '행은 아래에서 위로 뒤집고, 열은 하나 건너 하나만' 골라 출력하세요.
# 대괄호 한 번으로 끝냅니다. (temp[행규칙, 열규칙])
# 기대 출력: [[74.1 69.5 81.8]
#             [69.8 78.2 70. ]
#             [71.2 75.9 66.3]]

print("문제 1. 2차원 슬라이싱 두 방향 동시에")
reversed_temps = temp[::-1, :]  # 2차원 배열 슬라이싱
# print(reversed_temps)
print(reversed_temps[:, ::2])
print()

# ----------------------------------------
# 문제 2. 마스크에 axis 걸기
# ----------------------------------------
# 설비별로 '72도를 넘은 시점이 몇 번'인지 출력하세요.
# 기대 출력: [2 3 3]
print("문제 2. 마스크에 axis 걸기")
print((temp > 72.0).sum(axis=1))
print()

# ----------------------------------------
# 문제 3. 행 기준 편차 - 모양을 맞춰야 빠진다
# ----------------------------------------
# 각 설비의 '자기 평균'을 뺀 편차를 소수 둘째 자리까지 반올림해 출력하세요.
# 그냥 빼면 shapes 오류가 납니다. 왜 나는지 모양을 찍어 보고 해결하세요.
# 기대 출력: [[-1.2  -3.9   3.5   7.7  -6.1 ]
#             [-5.4  -2.8   3.   10.4  -5.2 ]
#             [-0.62 -3.82 -5.22  2.58  7.08]]

print("문제 3. 행 기준 편차 - 모양을 맞춰야 빠진다")
machine_avg = temp.mean(axis=1)
avgs_arr0 = temp[0] - machine_avg[0]
avgs_arr1 = temp[1] - machine_avg[1]
avgs_arr2 = temp[2] - machine_avg[2]
minus = np.array([avgs_arr0, avgs_arr1, avgs_arr2])
print(minus)
print()

# ----------------------------------------
# 문제 4. 표준화 (z-점수)
# ----------------------------------------
# temp 전체를 (값 - 전체평균) / 전체표준편차 로 바꾸고 소수 둘째 자리까지 반올림해
# 출력하세요. '평균에서 표준편차 몇 개만큼 떨어졌나'를 보는 방식입니다.
# 기대 출력: [[-0.54 -1.05  0.34  1.12 -1.46]
#             [-0.81 -0.32  0.77  2.15 -0.77]
#             [-0.   -0.6  -0.86  0.6   1.44]]

print("문제 4. 표준화 (z-점수)")
a = round(temp.mean(), 2)
s = round(temp.std(), 2)
znum1 = np.round((temp[0] - a) / s, 2)
znum2 = np.round((temp[1] - a) / s, 2)
znum3 = np.round((temp[2] - a) / s, 2)
temp_new = np.array([znum1, znum2, znum3])
print(temp_new)
print()


# ----------------------------------------
# 문제 5. 옆으로 이어 붙이고 뒤쪽만 보기
# ----------------------------------------
