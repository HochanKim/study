#

import numpy as np

# 설비 M-102에 붙은 센서 3종의 시점 10개 기록입니다. 이 파일 전체에서 씁니다.
#             t0    t1    t2    t3    t4    t5    t6    t7    t8    t9
vib = np.array([30.2, 29.8, 30.5, 30.1, 58.0, 29.9, 30.4, 55.2, 30.0, 30.3])  # 진동
temp = np.array([70.1, 69.8, 88.5, 70.2, 91.0, 70.5, 69.9, 70.3, 70.0, 69.7])  # 온도
press = np.array([5.1, 5.0, 5.2, 4.9, 5.1, 5.0, 5.3, 9.8, 5.0, 5.1])  # 압력

# 문제 10에서 씁니다.
t10 = np.array([[30.6], [70.4], [5.2]])


# ----------------------------------------
# 문제 1. 따로 노는 센서를 한 표로 쌓기
# ----------------------------------------
# 세 센서를 위에서부터 진동, 온도, 압력 순으로 쌓아 sensors 2차원 배열을 만들고,
# shape와 센서별 평균(소수 둘째 자리 반올림)을 차례로 출력하세요.
# 반복문 없이 한 줄로 쌓습니다.
# 기대 출력: (3, 10)
#            [35.44 74.    5.55]
print("문제 1. 따로 노는 센서를 한 표로 쌓기")
sensors = np.array([vib, temp, press])
# print(sensors)
#  vib =>   [[30.2 29.8 30.5 30.1 58.  29.9 30.4 55.2 30.  30.3]
#  temp =>  [70.1 69.8 88.5 70.2 91.  70.5 69.9 70.3 70.  69.7]
#  press => [ 5.1  5.   5.2  4.9  5.1  5.   5.3  9.8  5.   5.1]]


print(sensors.shape)
# 센서별 => 행 => axis=1
print(np.round(sensors.mean(axis=1), 2))
print()
# ----------------------------------------
# 문제 2. 두 방향 동시에 자르기
# ----------------------------------------
# sensors에서 '행은 아래에서 위로 뒤집고, 열은 하나 건너 하나' 골라 출력하세요.
# 대괄호 한 번으로 끝냅니다.
# 기대 출력: [[ 5.1  5.2  5.1  5.3  5. ]
#             [70.1 88.5 91.  69.9 70. ]
#             [30.2 30.5 58.  30.4 30. ]]
# print(sensors[::-1, :])
print("문제 2. 두 방향 동시에 자르기")
print(sensors[::-1, ::2])
print()

# ----------------------------------------
# 문제 3. 센서별 변동 폭
# ----------------------------------------
# 센서별로 '가장 큰 값 - 가장 작은 값'을 소수 둘째 자리까지 반올림해 출력하세요.
# 기대 출력: [28.2 21.3  4.9]
print("문제 3. 센서별 변동 폭")
print(np.round(sensors.max(axis=1) - sensors.min(axis=1), 2))
print()

# ----------------------------------------
# 문제 4. 축을 반대로 걸어 보기
# ----------------------------------------
# 이번엔 센서가 아니라 '시점별'로 센서 3종의 평균을 소수 둘째 자리까지 반올림해
# 출력하세요. 결과가 10개 나와야 합니다.
# 기대 출력: [35.13 34.87 41.4  35.07 51.37 35.13 35.2  45.1  35.   35.03]
print("문제 4. 축을 반대로 걸어 보기")
# 시점별 => 열 => axis=0
y_means = sensors.mean(axis=0)
print(np.round(y_means, 2))
print()

# ----------------------------------------
# 문제 5. 센서마다 자기 울타리
# ----------------------------------------
# 센서별로 IQR, 위 울타리(Q3 + 1.5 x IQR), 아래 울타리(Q1 - 1.5 x IQR)를
# 소수 둘째 자리까지 반올림해 차례로 출력하세요.
# 센서마다 정상 범위가 다르므로 axis를 걸어야 합니다.
# 기대 출력: [0.45 0.52 0.17]
#            [31.15 71.24  5.44]
#            [29.35 69.14  4.74]
print("문제 5. 센서마다 자기 울타리")
q1 = np.percentile(sensors, 25, axis=1)
# print(q1)
q3 = np.percentile(sensors, 75, axis=1)
# print(q3)
iqr = np.round(q3 - q1, 2)
print(iqr)

top_bnd = np.round(q3 + 1.5 * iqr, 2)
btm_bnt = np.round(q1 - 1.5 * iqr, 2)
print(top_bnd)
print(btm_bnt)
print()
# ----------------------------------------
# 문제 6. 울타리를 표 전체에 씌우기 - 모양을 맞춰야 걸린다
# ----------------------------------------
# 울타리를 벗어난 자리를 True로 표시한 mask를 만들고, 센서별 이상 개수를 출력하세요.
# 울타리는 센서당 하나(1차원), 표는 2차원입니다. 그냥 비교하면 shapes 오류가 납니다.
# 기대 출력: [2 2 1]
print("문제 6. 울타리를 표 전체에 씌우기 - 모양을 맞춰야 걸린다")
mask = (sensors < btm_bnt[:, None]) | (sensors > top_bnd[:, None])
# print(mask)
# print(sensors.shape)
# print(top_bnd.shape, top_bnd[:, None].shape)
print(np.sum(mask, axis=1))
print()

# ----------------------------------------
# 문제 7. 어디서 터졌나
# ----------------------------------------
# mask에 걸린 자리의 '센서 번호', '시점 번호', '원래 값'을 차례로 출력하세요.
# 번호 두 줄은 대괄호 한 번으로 같이 얻을 수 있습니다.
# 기대 출력: [0 0 1 1 2]
#            [4 7 2 4 7]
#            [58.  55.2 88.5 91.   9.8]
print("문제 7. 어디서 터졌나")
sensor_num, time_num = np.where(mask)
orgin_values = sensors[mask]
print(sensor_num)
print(time_num)
print(orgin_values)
print()

# ----------------------------------------
# 문제 8. 두 조건을 겹쳐 보기
# ----------------------------------------
# 진동과 온도가 '동시에' 이상이던 시점 번호를 출력하고,
# 이어서 세 센서 중 '하나라도' 이상이던 시점 번호를 출력하세요.
# 기대 출력: [4]
#            [2 4 7]
print("문제 8. 두 조건을 겹쳐 보기")
# print(np.where(mask))
# => 이상값이 검출된 행: array([0, 0, 1, 1, 2]) => sensor_num
# => 이상값이 검출된 열: array([4, 7, 2, 4, 7]) => time_num

# 동시에 True(이상값)를 만족하는 자리수 찾기
both_mask = mask[0] & mask[1]
print(np.where(both_mask)[0])
print(np.unique(time_num))
print()

# ----------------------------------------
# 문제 9. 이상치를 걷어내고 다시 재기
# ----------------------------------------
# mask에 걸린 자리를 그 센서의 중앙값으로 바꾼 배열을 fixed 라 하고,
# fixed의 센서별 평균을 소수 둘째 자리까지 반올림해 출력하세요.
# if문 없이 조건 하나로 통째로 바꿉니다. 문제 1의 평균과 비교해 보세요.
# 기대 출력: [30.17 70.08  5.08]
print("문제 9. 이상치를 걷어내고 다시 재기")
middle = np.median(sensors, axis=1)
# print(middle)
fixed = np.where(mask, middle[:, None], sensors)
# np.where(이상값 위치, 해당 센서의 중앙값(3, 1), 정상이면 원래 값)
print(fixed.mean(axis=1))
print()

# ----------------------------------------
# 문제 10. 새 시점을 옆에 붙이고 뒤쪽만 보기
# ----------------------------------------
# fixed 오른쪽에 t10을 이어 붙이고, 합친 배열의 shape와
# '마지막 두 시점만'의 센서별 평균(소수 둘째 자리 반올림)을 차례로 출력하세요.
# 기대 출력: (3, 11)
#            [30.45 70.05  5.15]
print("문제 10. 새 시점을 옆에 붙이고 뒤쪽만 보기")
# t10 = np.array([[30.6], [70.4], [5.2]])
add_vib = np.concatenate([fixed[0], t10[0]])
add_temp = np.concatenate([fixed[1], t10[1]])
add_press = np.concatenate([fixed[2], t10[2]])

# 뒤에 붙인 값들 모아서 배열로 묶기
fixed = np.array([add_vib, add_temp, add_press])
# print(fixed)
print(fixed.shape)
# fixed[전체 행, 9번째 열 이후부터 끝까지(인덱스 10, 11)]
print(fixed[:, 9:].mean(axis=1))
