"""
[수백 개의 값을, 왜 몇 개 숫자로 줄일까?]

설비 한 대에서 하루 온도를 재면 값이 수백 개, 여러 설비를 며칠 돌리면
수천, 수만 개로 불어난다. 이 숫자를 그대로 늘어놓아서는 설비 상태를 알 수 없음.
사람 눈은 수백 개 숫자를 한 번에 못 읽음

그래서 많은 값을 몇 개의 '대표 숫자'로 압축나느데 -> 이걸 '요약'이라고 함
=> 요약은 딱 세 물음에 답하는 일
- 중심: 값들이 대개 어디쯤 모여 있나? (평균, 중앙값)
- 흩어짐: 중심 주위에 촘촘한가? 넓게 퍼졌나? (범위, IQR, 표준편차)
- 이상치: 유난히 튀는 값은 없나? (z-score)

=> 요약이 없으면 비교도, 판단도 없다. 두 설비를 견주려면 원본 수천 개가 아니라 대표 숫자 몇 개를 나란히 놓아야 함

이번 단원은 '수학'이 실제로 있는 구간
=> 직관 먼저 잡고, 공식은 참고용으로
=> 값은 전부 numpy 함수가 계산해 주니, 우리는 결과를 '읽는'데 집중
"""

import numpy as np

# ----------------------------------------------
# 중앙값 - 크기순으로 놓았을 때 '한가운데' 값
# ----------------------------------------------
"""
[중심을 재는 방법이 평균 하나뿐일까?]
데이터의 중심을 말할 때 가장 먼저 떠올리는 건 평균
그런데 중심을 짚는 방법이 평균 하나만은 아니다
값을 크기순으로 줄 세웠을 때 딱 한가운데 오는 값, 이것도 훌륭한 중심 => 이 값이 '중앙값'(median)
=> 평균은 배열에 점을 찍어 temps.mean()으로 불렀지만, median은 np.median(tems) 형태로 사용
"""
temps = np.array([82, 85, 84, 86, 83, 88])
print("중앙값(짝수 개):", np.median(temps))
# => "짝수 개"라 가운데가 없으니, 가운데 두 값의 평균으로 계산
print("평균값(짝수 개):", temps.mean())
print()

odd = np.array([75, 82, 88, 91, 95])
print("중앙값(홀수 개):", np.median(odd))
print()

# ----------------------------------------------
# 평균 vs 중앙값 - 이상치가 하나 섞이면?
# ----------------------------------------------
"""
[왜 중심을 재는 대표값이 두 개나 필요할까?]
평균과 중앙값이 크게 갈라지는 상황을 직접 만들어,
각각이 언제 쓸모 있는지 눈으로 확인하기
=> 핵심은 '이상치' (튀는 값 하나)에 두 값이 어떻게 반응하는가?
"""

# 깨끗한 온도 여섯 값 - 평균과 중앙값이 거의 겹침
clean = np.array([82, 85, 84, 86, 83, 88])
print("깨끗한 값 - 평균:", clean.mean())
print("깨끗한 값 - 중앙값:", np.median(clean))
print()

# 마지막 값을 999로 바꿔 '이상치'를 하나 심기 (ex. 센서 접촉 불량 상황 등)
bad = np.array([82, 85, 84, 86, 83, 88, 999])
print("999 섞임 - 평균:", bad.mean())
print("999 섞임 - 중앙값:", np.median(bad))
# => 여기가 핵심
#   : 평균은 84.7 -> 215.28로 크게 튀어 오름
#   : 하지만 중앙값은 85 그대로
# ====> 크기순으로 세우면 999는 맨 끝으로 밀릴 뿐, 한 가운데를 차지할 수 없음
print()

# 정리:
#  - 평균: 모든 값을 계산에 넣음 -> 이상치에 '민감'(약함)
#  - 중앙값: 순서만 봄 -> 이상치에 '강함'
# => 두 값이 크게 벌어지면? -> 데이터 어딘가에 이상치가 숨어 있다는 신호

# ----------------------------------------------
# 분위수 - '하위 몇 퍼센트' 지점의 값
# ----------------------------------------------
"""
[알고 싶은 지점이 꼭 한가운데만은 아니다]
중앙값은 데이터를 정확히 반으로 가르는 '하위 50% 지점'
그런데 하위 25%는 어디인지, 상위 10%에 드는 값은 얼마부터 인지 궁금한 경우가 있다
이렇게 하면 하위 몇 퍼센트 지점의 값을 뽑는 것이 '분위수'(Percentile)이다

값을 작은 것부터 큰 것까지 줄 세운 뒤 100등분 한다 생각하고,
np.percentile(배열, 백분위 숫자)로 그 지점 값을 뽑음
"""

scores = np.array([70, 74, 78, 80, 82, 86, 90, 96])
print("50% 지점:", np.percentile(scores, 50))
# => 50% 지점의 값을 가져옴, 중앙값과 같은 뜻
print("90% 지점:", np.percentile(scores, 90))
print()
# => 하위 90% 지점의 값을 가져옴 = 상위 10%가 시작되는 경계
# 이 값(91.8)보다 큰 값은 전체의 10% 뿐
#
# 평균 중앙값이 '중심 한 점'을 말한다면,
# 분위수는 데이터를 따라 '원하는 위치'의 값을 자유롭게 뽑아낸다


# ----------------------------------------------
# 사분위수 Q1 Q# IQR
# ----------------------------------------------
"""
[분위수 중 실무에서 가장 자주 쓰는 것]
데이터를 넷으로 나누는 사분위수
=> 크기순으로 줄을 4등분 하면 세 경계가 생김
- 하위 25% 지점 = 1사분위수 Q1
- 하위 50% 지점 = 중앙값
- 하위 75% 지점 = 3사분위수 Q3
=> Q3에서 Q1을 뺀 폭을 IQR(사분위 범위)이라 부름
=> 수식(참고): IQR = Q3 - Q1
"""

q1 = np.percentile(scores, 25)
q3 = np.percentile(scores, 75)
print("Q1(하위 25%):", q1)  # 77.0
print("Q3(하위 75%):", q3)  # 87.0
print("IQR = Q3-Q1:", q3 - q1)  # 10.0
print()
# IQR이 뜻하는 것 = "가운데 50%"의 값들이 흩어진 폭
# => 양 끝 극단을 뺀 중간 절반이 얼마나 넓게 퍼졌는지를 한 숫자로 표현하는 것
#
# 중요: IQR은 Q1, Q3라는 '순서상 위치'로만 계산됨
# => 그래서 양 끝 이상치에 흔들리지 않는다, 이상치가 섞인 데이터의 흩어짐은 표준편차보다 IQR이 더 믿을만 한 정보


# ----------------------------------------------
# 데이터 범위 - max에서 min까지 '전체 폭'
# ----------------------------------------------
#
# 데이터가 얼마나 흩어졌는지를 재는 가장 단순한 방법은
# 양 끝을 보는 것

# 전체 범위 = 가장 큰 값 - 가장 작은 값
# 범위: max - min
print("범위(전체 폭):", scores.max() - scores.min())
# => 최대: 96 / 최소: 70이므로 범위는 26 -> 이 데이터가 70~96 사이에 흩어짐을 의미
#
# ※ 주의: 범위는 양 끝값 두 개만 의존해서 이상치에 약함
# => 999와 같은 이상한 값이 들어가면 범위가 많이 튄다 -> 그러므로 전체 폭(범위)과 가운데 절반 폭(IQR)을 함께 본다
# => 범위가 IQR보다 유난히 크면 -> 양 끝에 극단값이 있다는 신호

# 극단값은 줄 세웠을 때 혼자 저 멀리 떨어져 서 있는 값 -> 반 평균 키를 재는데 농구선수 2.4m가 꺼어든 상황

