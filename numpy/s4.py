"""
[대표값 지도]
- 중심: 평균, 중앙값 -> 데이터가 대개 어디에 모였는가?
==> (평균: 이상치 약함 / 중앙값: 이상치 강함)

- 위치: 분위 Q1, Q3 -> 사분면 경계가 어디부터?
- 폭: 범위, IQR -> 전체와 가운데 절반이 얼마나 퍼졌는가?
==> (범위: 이상치 약함 / IQR: 이상치 강함)

☆ 관통하는 하나의 축 = '이상치에 강한가? 약한가?'
==> 실무에선 두 종류(약한 것, 강한 것) 나란히 구해 갈라짐을 살핌
"""

