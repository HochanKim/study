"""
[표준편차, 이 숫자가 정확히 무슨 뜻인가?]
범위와 IQR이 '양 끝 사분면'으로 흩어짐을 쟀다면
표준편차(std)는 '평균을 기준'으로 흩어짐을 잰다.
각 값이 평균에서 평균적으로 얼마나 떨어졌는지의 크기
=> 직관적으로 보면 표준편차가 평균에서 데이터가 '평균적으로 떨어진' 정도
"""
