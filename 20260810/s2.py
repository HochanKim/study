# ============================================
# 기울기와 y절편 구하기
# ============================================
# 두 점 (x1, y1), (x2, y2)를 지나는 직선의 기울기
# => a = y의 증가량 / x의 증가량 = (y2 - y1) / (x2 - x1)


def ss(x1, y1, x2, y2):
    # 두 점을 지나는 직선의 기울기
    return (y2 - y1) / (x2 - x1)


def line_eq(x1, y1, x2, y2):
    # 두 점을 지나는 직선의 식을 구해서 (기울기, y절편)을 돌려준다
    a = ss(x1, y1, x2, y2)
    b = y1 - a * x1
    return a, b


# 두 점 (1, 3), (4, 9)를 지나는 직선
print(line_eq(1, 3, 4, 9))

# ============================================
# x절편 구하기  (y = 0이 되는 x)
# ============================================
# ax + b = 0 -> x = -b/a


def x_in(a, b):
    if a == 0:
        return None
    return -b / a


print("y = 2x + 1의 x 절편: ", x_in(2, 1))
print("y = 3의 x 절편: ", x_in(0, 3))


