# 5. for문과의 차이점
# ============================================
# for : 반복 횟수를 "이미 알고 있을 때" (리스트, range 등)
# while: 반복 횟수를 "모를 때" (조건이 만족될 때까지)

for i in range(1, 4):
    print("for:", i)

i = 1
while i < 4:
    print("while", i)
    i += 1
    print("다음 단계", i)
