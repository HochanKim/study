# 변수란?
# - 값에 이름을 붙이는 "이름표"
# - 값을 메모리에 저장해 두고, 나중에 그 이름으로 다시 꺼내 쓰는 것

# 변수 선언 예시
age = 25
# 변수 age에 25라는 값을 저장
# '=' 기호를 사용하여 변수에 값을 할당: 대입연산자 (수학의 '같다'와 개념이 다름)
print(age)  # 변수 age의 값을 출력

# 위에서 아래로 순서대로 실행
score = 90
score = 100  # 변수 score에 100을 다시 할당
print(score)  # 변수 score의 값을 출력

# 자기 자신을 이용해서 바꾸기
count = 10
count = (
    count + 5
)  # 변수 count에 기존 값 10에 5를 더한 값을 다시 할당, 오른쪽 연산을 먼저 계산하고 왼쪽 변수에 할당
print(count)  # 변수 count의 값을 출력

# 복합 대입 연산자 (위와 똑같은 뜻인데 더 간단하게 표현)
count += 5  # 변수 count에 5를 더한 값을 다시 할당
print(count)  # 변수 count의 값을 출력

# 파이썬은 타입을 미리 안 정해도 됨 (동적 타이핑)
# 다른 언어: int age = 25; <= 자료형을 직접 선언해야 함 (Java, C, C++, C# 등)
# 파이썬: age = 25 <= 자료형의 값을 보고 알아서 판단

x = 10  # 정수형 (int)
print(x, type(x))  # 변수 x의 값과 자료형을 출력

x = "Hello, world"  # 같은 변수에 문자열을 넣어도 에러가 안남
print(x, type(x))  # 변수 x의 값과 자료형을 출력

# 단점: 편리하지만, 실수로 타입이 바뀌면 버그가 될 수 있음


# 변수명 규칙
# 가능한 사례
user_name = "누군가"  # 0 영문 소문자 + 언더바('_'): 스네이크 케이스 (파이썬에서 가장 권장되는 형태)
userName = "아무개"  # 0 카멜 케이스 (파이썬에서 잘 사용하지 않는 형태)
_private = "값"  # 0 앞에 언더바('_') 오는거 괜찮음
name2 = "홍길동"  # 0 숫자가 끝에 오는거 괜찮음
이름 = "김호찬"  # 0 가능하지만 사용하면 안됨

# 불가능한 사례
# 2name = "투네임"
# user name = "이름표" // 띄어쓰기 불가
# user-name = "이름표" // 하이픈 불가
# class = "클래스" // 파이썬에서 이미 사용하는 단어(예약어)는 불가
# if, else, for, elif, while, def 등등

Age = 1
age = 2
AGE = 3
print(Age, age, AGE)

# 참고
# 참/거짓 변수(bool형)는 'is_', 'has_'로 시작하면 읽기 좋음
is_logged_in = True


# 상수 (변하지 않는 값)
# 파이썬에는 진짜 상수가 없어서 "대문자"로 쓰면 바꾸지 말자고 약속
PI = 3.141592718
MAX_USER = 100
TAX_RATE = 0.33

# PI = int(PI), 문법상 바꿀 수 있지만, 팀 규칙상 바꾸면 안되는 값


# 순서대로 하나씩 값 대입
a, b, c = 4, 5, 6
print(a, b, c)

# 여러 변수에 같은 값을 한꺼번에 대입
x = y = z = 7
print(x, y, z)

# 두 변수의 값을 서로 바꾸기 (파이썬 특유의 깔끔한 문법)
first, second = "A", "B"
first, second = second, first  # 임시 변수 없이 한 줄로 교환
print(first, second)


# 값이 없음을 나타내는 None
result = None  # '아직 값이 정해지지 않았다'는 뜻으로 사용
print(result)
print()

# == 변수를 문자열에 끼워 넣기 (f-string) ==
name = "펭수"
age = 20

print("이름 : " + name)
print(
    "나이 : " + str(age)
)  # '문자열 + 숫자형"은 에러, 숫자형을 str()로 감싸서 문자로 변환하면 OK

# 가장 편한 방법: 문자열 앞에 f를 붙이고 {} 안에 변수명 쓰기
print(f"{name}님은 {age}살 입니다.")
print(f"내년에는 {age + 1}살 입니다.")
print()

# 변수 삭제
temp = "임시용"
del temp
temp = "새로 추가"
print(temp)
print()


# (심화) 변수는 값을 '담는 상자'가 아니라 값을 '가리키는 화살표'
a = [1, 2, 3]
b = a  # b도 '같은' 리스트를 가리킴 (복사가 아님)
b.append(4)  # b를 통해 리스트를 수정하면
print(a)

# 숫자 문자열은 값을 바꿀 수 없어서 이런 현상이 안 생깁니다.
n1 = 10
n2 = n1
print(n2)
n2 = 20  # 변수 'n2'가 새로운 값 20을 가리킬 뿐, n1의 값은 변하지 않는다.
print(n1)
print(n2)
