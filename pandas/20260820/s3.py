# 배열이 필요한 이유는?
# -> 지금까지 값 여러 개는 전부 리스트에 담아서 관리 및 생성을 했고
#   전체를 계산하려면 빈 리스트 하나 준비하고, for로 값을 하나씩 꺼내 계산해서
#   append 하는 것을 반복

# -> 온도 리스트의 모든 값에 그냥 3을 더하고 싶을 뿐인데도
#   빈 그릇 준비 + for + append, 매번 여러 줄이 필요했다
#   게다가 설비 한 대가 1초에 한 번 온도를 재면 하루 8만 개, 열 대면 수십만 개가 필요하다
#   하나씩 꺼내 계산하면 눈에 띄게 느려진다

# 리스트로 온도 전체에 3을 더하려면? (numpy 사용 이전)
temps_list = [62.1, 63.5, 71.8]
result = [] # 빈 그릇부터 준비

for t in temps_list:  # for로 하나씩 꺼내서
  result.append(t + 3)  # 더한 뒤 담는다
print(result) # => [65.1, 66.5, 74.8]
# => 값 세 개인데도 세 줄을 써야한다


