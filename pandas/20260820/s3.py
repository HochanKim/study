# Numpy - 수치 계산 라이브러리
# -------------------------------------------------------------
# [NumPy가 뭔가요?]
# - 대량의 수치를 빠르고 간결하게 다루는 파이썬 라이브러리
#   Numerical Python(수치 계산을 위한 파이썬)의 줄임말
#   '넘파이'라고 읽는다

# 파이썬에 기본으로 든 것이 아닌 누군가가 만들어 배포한 도구
# random이나 math를 import해서 썼듯이, NumPy도 import해서 쓴다
# => 이게 데이터 분석과 AI의 '밑바닥'이기 때문에
#   데이터 분석 도구도, 인공지능 모델 다루는 도구도 대부분 'NumPy' 배열 위에서 돌아간다
#   측정값, 이미지 픽셀, 모델의 숫자가 전부 배열로 표현됨


# NumPy는 언제나 'np'라는 별칭으로 가져오는 게 전세계 관례
# 문법상 npy나 num으로 지어도 오류는 안 나지만, 어떤 책도 예제도 전부 np로 쓴다
# np로 보면 누구나 NumPy를 사용한다는 의미

import numpy as np
# -------------------------------------------------------------
# 배열 ndarry - 수치를 담는 그릇
# -------------------------------------------------------------

# NumPy가 수치를 담는 그릇을 '배열(Array)'라고 부릅니다
# => 어떤 것이든 담는 리스트와 다르게 '배열'은 '같은 종류의 수치'들만 한 덩어리로 묶어 담는 전용 그릇을 의미
# => 온도 값 여럿, 진동 값 여럿처럼 같은 자료형의 숫자를 나란히 담는다

# 정식 이름은 ndarray, 'n차원 배열(n-dimensioanl array)'
# => 한줄로 늘어선 형태뿐 아니라, 표처럼 가로세로로 펼쳐진 형태까지 담을 수 있어서 '차원'이라는 말이 들어감

# 1차원 배열 = [0, 1, 2]
# 2차원 배열 = [[0, 1, 2], [3, 4, 5]]
# => 같은 종류 수치만 한 덩어리로 모아 두면 그 덩어리 전체에 계산을 '한 번에' 빠르게 걸 수 있기 때문


# -------------------------------------------------------------
# np.array로 배열 만들기
# -------------------------------------------------------------

# 배열 만들기의 가장 기본은 손에 익은 리스트를 배열로 바꾸는 것
# np.array에 '값들을 담은 리스트'를 넣어 부르면 배열이 된다
temps = np.array([62.1, 63.5, 71.8])
print(temps) # => [62.1 63.5 71.8]
# 값 사이에 쉼표가 없음
# 쉼표로 구분되는 리스트와 다르게, 배열은 공백으로 구분된다
# => 이게 바로 '배열'이란 것 (리스트와의 차이점)

# 핵심: 대괄호([])가 중요하다
# => np.array에 넣는 건 값 하나하나가 아닌
# 소괄호 안에 대괄호가 한 번 더 들어가는 '이중 괄호' 모양
# np.array([62.1 63.5 71.8])

# ※ 리스트와 뭐가 다른가?
# => 겉보기엔 둘 다 값을 순서대로 담지만, 쓰임이 다르다
# """
#             리스트          배열
# 구분      쉼표(,)           공백
# 담는 값   여러 종류 섞임   같은 자료형만
# 계산      
# 대량속도    느림            빠름
# 겉모습    쉼표 구분         공백 구분


# => 배열은 리스트를 '대체'하는 것이 아니고
# 섞인 값을 하나씩 다룰 땐 리스트
# 같은 수치를 대량으로 계산할 땐 배열
# 실제로는 리스트로 모아 뒀다가 np.array로 바꿔 계산하는 식으로 
# 둘을 함께 사용한다
# """

# 맨 앞에서 리스트로 3을 더할 때 for가 세 줄 필요했지만
# 배열은 for 없이 한 줄이다
print(temps + 3)

# 리스트로 하던 것을 배열은 통째로 한 번에 건다
# -------------------------------------------------------------
# 같은 자료형만 담긴다 - dtype
# -------------------------------------------------------------

# 배열은 모든 값을 '같은 자료형'으로 통일해서 담는다
# 리스트는 정수, 문자열, 실수를 섞어 담지만
# 배열 안의 값은 전부 같은 형이여야 한다

mix = np.array([1, 2, 3.0])
print(mix)  # [1. 2. 3.]
# => 정수 1, 2가 '1.', '2.'처럼 '실수'로 바뀌어 나온다
#   실수가 하나라도 섞이면, 정수를 실수 쪽으로 끌어올려 전체를 통일함
#   이렇게 배열 전체가 공유하는 자료형을 'dtype'이라 부른다

print(mix.dtype) # float64 = 64비트 실수
# 이 '통일'이 배열을 빠르게 만든다
# NumPy가 확신하니까, 값마다 종류를 따질 필요 없이 전체를 같은 방식으로 한 번에 계산함

# -------------------------------------------------------------
# dtype 확인과 지정
# -------------------------------------------------------------
# => 배열이 어떤 자료형인지 궁금하면 이름 뒤에 점 찍고 dtype이라 적는다
# "정보를 꺼내 보는 것"이라는 소괄호는 안 붙인다

print(temps.dtype)  # float64
# => 소수점 있는 온도 값이라 실수로 잡힘

print(np.array([82, 79, 85]).dtype) # int64
# 소수점 없는 정수는 int64로 잡힌다
# NumPy가 넣는 값을 보고 알맞은 자료형을 스스로 정한다

# 자동에 맡기지 않고 직접 지정할 수 있다
# => np.array를 부를 때 dtype 옵션을 넘기면 된다
print(np.array([1, 2, 3], dtype=float)) # [1. 2. 3.]
# 정수 1, 2, 3을 넣어도 float으로 지정하면 실수 배열이 됨
# 정수 데이터지만 앞으로 나눗셈 같은 실수 계산을 할 예정일 때 이렇게 미리 실수로 담아 둔다
# .dtype -> 속성을 확인 할 때
# dtype -> 속성을 지정할 때 

# -------------------------------------------------------------
# 0으로, 1로 채운 배열 - zeros, ones
# -------------------------------------------------------------

# 배열 만들기에 늘 리스트가 필요한 건 아니다
# => 특정 값으로 미리 채운 배열을 곧바로 만드는 도구가 있음

# np.zeros는 0으로 채움
print(np.zeros(3))  # [0. 0. 0.]
# 괄호 안의 3은 '값'이 아니라 '개수'이다, 0을 세 개 담아라

# np.ones는 1로 채움
print(np.ones(3)) # [1. 1. 1.]
# 0과 1이 0., 1. 처럼 소수점 붙어 '실수'로 나옴
# zeros와 ones 기본이 실수 배열이다

# '계산 결과를 담을 빈 그릇'을 미리 준비할 때 자주 씀
# 리스트로 합 구할 때 total = 0으로 시작했듯이
# 배열을 채워 나갈 때 0으로 채운 배열을 먼저 만들어 두고 시작함

# -------------------------------------------------------------
# 연속 숫자 배열 - arange
# -------------------------------------------------------------
# 0 1 2 3 처럼 연속된 숫자로 채운 배열이 필요할 땐 np.arange
# array range, 즉 '배열 버전의 range'라는 이름

print(np.arange(5)) # [0 1 2 3 4]
# 0부터 5 '직전'까지, 끝값 5는 포함 안된다 (= range랑 같음)

# 시작, 끝, 간격을 넣는 방식도 range와 똑같음
print(np.arange(0, 10, 2))  # [0 2 4 6 8]
# 0부터 10 직전까지 2씩 건너뛰며 만듦

# range와 다른 점은 '결과물'의 차이
# => range는 for와 함께 도는 데 썼지만
# => arange는 연속 숫자를 '배열'로 돌려준다
# ==> 만들어진 순간까지 배열의 모든 성질을 그대로 쓴다


# -------------------------------------------------------------
# 균등 분할 - linspace
# -------------------------------------------------------------

# arange가 '간격'을 정해 만들었다면, linspace는 '개수'를 정해서 만듦
# 시작값과 끝값 사이를 몇 등분할지 정하면 균등하게 나눠 돌려줌

print(np.linspace(0, 100, 5)) # [0. 25. 50. 75. 100.]
# 시작 0, 100, 25 // 0으로 시작해서 25씩 100까지 숫자를 표현
# 똑같은 간격 25로 나뉜 다섯 값

# 여기서 arange와 결정적으로 다른 점
# => linspace는 '끝값 100을 포함'합니다
# => arange는 끝 직전까지만 담지만, linspace는 시작과 끝을 양 끝에 두고 그 사이를 나눔

# 나눠 쓰는 기준
# 간격이 정해져 있으면 -> arange (2씩 건너뛴 값)
# 개수가 정해져 있으면 -> linspace (0~100을 다섯 등분)


# -------------------------------------------------------------
# 배열의 모양 - shape
# -------------------------------------------------------------

# 배열을 만들었다면 '생김새'를 읽을 줄 알아야 한다
# 첫 번째 정보가 모양, shape
# 정보를 꺼내 보는 것이라 소괄호는 안 붙인다

print(temps.shape) # -> (3,)
# 값이 세 개 들어 있는 1차원 배열이라는 뜻
# 3은 값의 개수
# 3 뒤에 쉼표는 뭐냐> => '여러 정보를 담을 수 있는 형태, 그 중 하나만 채워졌다'는 표시
# 1차원 배열은 모양 정보가 '개수' 하나 뿐이라 (3,)으로 나옴

# 2차원 배열은 (행, 열) 두 숫자로 나온다
# => 1차원 [62.1, 63.5, 71.8] -> shape (3,)
# => 2차원 [[1 2 3] [4 5 6]] -> shape(2, 3) <- 행 2, 열 3

# -------------------------------------------------------------
# 크기 size와 차원 ndim
# -------------------------------------------------------------
# shape 말고도 생김새를 알려 주는 정보가 둘 더 있다
# size는 배열이 담은 '전체 값의 개수'이다
print(temps.size) # 3
# 값이 세 개라는 뜻, 소괄호 없이 이름만 적는다

# ndim은 배열이 '몇 차원'인지
print(temps.ndim) # 1
# 이 배열이 1차원이라는 뜻
# 한 줄로 늘어선 배열이라 차원이 1이다
# 1차원 배열은 값이 몇 개은 ndim이 언제나 1로 나온다

# shape => 모양
# size => 전체 개수
# ndim => 차원
# 1차원에서는 이 셋이 사실상 같은 이야기를 다른 각도로 말함
# 굳이 구분해 배우는 건, 2차원 배열에서 이들이 서로 다른 값으로 갈라진다

# -------------------------------------------------------------
# 센서 측정값을 배열로 (배운 것 한 흐름)
# -------------------------------------------------------------
# 현장에서 센서가 뱉는 온ㄷ, 진동, 입력, 생산량이 전부 이렇게 들어간다
temps = np.array([62.1, 63.5, 71.8, 68.2, 65.9])

# 만들었으면 바로 정체를 확인한다
print(temps.dtype)  # float64
print(temps.shape)  # (5,) / 값 다섯 개인 1차원 배열
print(temps.size)   # 5 / 전체 다섯 개
print(temps.ndim)   # 1 / 1차원
# 측정값 뭉치를 받으면 일단 배열로 담고 shape과 dtype부터 확인
# 데이터를 다루는 사람의 기본기


