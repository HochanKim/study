#
#   [열 다루기]
#
#     df["열"]                  열 하나 (Series)
#     df[["열1", "열2"]]         열 여러 개 (DataFrame)
#     df["새열"] = df["A"] * df["B"]   계산해서 추가
#     df.rename(columns={...})   이름 바꾸기
#     df.drop(columns=[...])     열 지우기
#
#
#   [행 다루기]
#
#     df[df["열"] == 값]                조건 필터
#     df[(조건1) & (조건2)]              and
#     df[(조건1) | (조건2)]              or
#     df[df["열"].isin([...])]          목록에 포함
#     df[df["열"].str.contains("글자")]  문자 포함
#     df.sort_values("열", ascending=False)   정렬
#
#
