# 값 추가 하기
fruits = ["사과", "바나나"]
fruits.append("포도")  # 맨 뒤에 하나 (가장 많이 쓰는 기능)
print(fruits)
print()

fruits.insert(0, "딸기")  # 0번 자리에 끼워넣기
print(fruits)  # ["딸기", "사과", "바나나", "포도"]
print()

fruits.extend(["수박", "참외"])  # 다른 리스트 풀어서 이어붙이기
print(fruits)  # 뒤로 추가되어 이어붙임
print()

# --- append와 extend의 차이 ---
a = [1, 2]
a.append([3, 4])  # [1, 2, [3, 4]] / 리스트 값 그대로 넣기
print(a)
print()
b = [1, 2]
b.extend([3, 4])  # [1, 2, 3, 4] / 리스트를 풀어서 넣기
print(b)
print()

# '[0] * 5'로 초기 리스트 만들기
print([0] * 5)  # [0, 0, 0, 0, 0]
print([1, 2] + [3, 4])  # [1, 2, 3, 4] / +로 합치기
print()

# 값 삭제하기
fruits = ["사과", "바나나", "포도", "바나나"]
fruits.remove("바나나")  # 값이 중복되어 있으면 앞의 하나만 삭제한다
print(fruits)
print()

number = [10, 20, 30, 40]
last = number.pop()  # 리스트의 맨 끝값을 삭제하면서 그 값을 변수에 받음
print(last)  # 40 / [10, 20, 30]
print()

number = [10, 20, 30, 40]
del number[0]  # 지정한 위치의 값을 삭제
print(number)  # [20, 30, 40]
print()

number = [10, 20, 30, 40]
number.clear()  # 전체 비우기
print(number)
print()

# 정리
# -> remove(값): 값으로 삭제
# -> pop(위치): 위치로 삭제 + 삭제한 값을 돌려줌
# -> del 리스트명[인덱스 번호]: 해당 인덱스 번호에 해당하는 값을 삭제
# -> clear(): 전체 리스트 값을 삭제 (빈 대괄호만 남김)


