# 음수 인덱스에서 '-1'번째는 항상 원소 마지막 값

# 잘라내기 - 슬라이싱
number = [10, 20, 30, 40, 50]
print(numbers[1:3])  # [20, 30]  // 끝 번호는 포함하지 않음
print(numbers[:3])  # [10, 20, 30]  // 처음(0)부터 (끝 번호 -1)번째 까지 값을 출력
print(numbers[2:])  # [30, 40, 50]  // 인덱스 두 번째(2)부터 끝까지 값을 출력
print(numbers[-2:])  # [40, 50]  // 음수 인덱스, 뒤에서 두 개
print(numbers[::2])  # [10, 30, 50] // 원소 두 칸씩 건너뛰어 출력

# [::-1]이면 리스트 원소가 뒤집혀짐 ('reverse()'와 같은 기능)
print(numbers[::-1])  # [50, 40, 30, 20, 10]
# reverse()와 달리 원본을 건드리지 않고 새 리스트를 생성
# 문자열에도 똑같이 적용 가능: "안녕하세요"[::-1]

# 리스트는 수정이 가능
# -> 문자열과의 결정적 차이
