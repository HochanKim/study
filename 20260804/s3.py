print(", ".join(fruits))  # 사과, 바나나, 포도
print("-".join(fruits))  # 사과-바나나-포도

# -> 출력할 때 join()을 쓰면 훨씬 보기 좋습니다.
print(fruits)  # 투박한 형태의 리스트 / ["사과", "바나나", "포도"]
print(", ".join(fruits))  # 깔끔한 형태로 출력 / 사과, 바나나, 포도
